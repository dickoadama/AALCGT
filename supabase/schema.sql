CREATE TABLE IF NOT EXISTS public.profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id UUID NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
    username TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    email TEXT NOT NULL DEFAULT '',
    phone TEXT NOT NULL DEFAULT '',
    role TEXT NOT NULL DEFAULT 'membre' CHECK (role IN ('membre', 'admin', 'superadmin')),
    bureau_role TEXT NOT NULL DEFAULT '',
    permissions_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    profile_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS profiles_username_lower ON public.profiles (LOWER(username));
CREATE UNIQUE INDEX IF NOT EXISTS profiles_one_superadmin ON public.profiles (role) WHERE role = 'superadmin';
CREATE UNIQUE INDEX IF NOT EXISTS profiles_one_bureau_role ON public.profiles (bureau_role) WHERE bureau_role <> '';

CREATE TABLE IF NOT EXISTS public.app_data (
    data_key TEXT PRIMARY KEY,
    data_json JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.app_settings (
    setting_key TEXT PRIMARY KEY,
    setting_value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT PRIMARY KEY,
    sender_id BIGINT NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    receiver_id BIGINT NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (sender_id <> receiver_id)
);

CREATE TABLE IF NOT EXISTS public.archives (
    id BIGINT PRIMARY KEY,
    owner_id BIGINT REFERENCES public.profiles(id) ON DELETE SET NULL,
    recipient_id BIGINT REFERENCES public.profiles(id) ON DELETE SET NULL,
    payload JSONB NOT NULL
);

CREATE TABLE IF NOT EXISTS public.audit_logs (
    id BIGINT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    payload JSONB NOT NULL
);

CREATE TABLE IF NOT EXISTS public.admin_member_assignments (
    admin_id BIGINT NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    member_id BIGINT NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    PRIMARY KEY (admin_id, member_id)
);

CREATE OR REPLACE VIEW public.member_directory AS
SELECT
    id,
    username,
    name,
    email,
    phone,
    role,
    bureau_role,
    created_at,
    jsonb_strip_nulls(jsonb_build_object(
        'city', profile_json ->> 'city',
        'proStatus', profile_json ->> 'proStatus',
        'job', profile_json ->> 'job',
        'company', profile_json ->> 'company',
        'sector', profile_json ->> 'sector',
        'level', profile_json ->> 'level',
        'experience', profile_json ->> 'experience',
        'skills', profile_json ->> 'skills',
        'promo', profile_json ->> 'promo',
        'bio', profile_json ->> 'bio'
    )) AS profile_json_public
FROM public.profiles
WHERE is_active;

CREATE OR REPLACE FUNCTION public.current_profile_id()
RETURNS BIGINT
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT id FROM public.profiles
    WHERE auth_user_id = auth.uid() AND is_active
$$;

CREATE OR REPLACE FUNCTION public.current_username()
RETURNS TEXT
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT username FROM public.profiles
    WHERE auth_user_id = auth.uid() AND is_active
$$;

CREATE OR REPLACE FUNCTION public.is_superadmin()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.profiles
        WHERE auth_user_id = auth.uid() AND is_active AND role = 'superadmin'
    )
$$;

CREATE OR REPLACE FUNCTION public.has_permission(required_permission TEXT)
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.profiles
        WHERE auth_user_id = auth.uid() AND is_active AND (
            role = 'superadmin' OR
            (role = 'admin' AND permissions_json ->> required_permission = 'true')
        )
    )
$$;

CREATE OR REPLACE FUNCTION public.can_manage_finance()
RETURNS BOOLEAN
LANGUAGE SQL
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.profiles
        WHERE auth_user_id = auth.uid() AND is_active AND (
            role = 'superadmin' OR bureau_role = 'tresorier' OR
            (role = 'admin' AND permissions_json ->> 'manage_finance' = 'true')
        )
    )
$$;

CREATE OR REPLACE FUNCTION public.create_member_profile()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    supplied_username TEXT;
BEGIN
    supplied_username := COALESCE(NEW.raw_user_meta_data ->> 'username', split_part(NEW.email, '@', 1));
    IF supplied_username !~ '^[A-Za-z0-9._-]{3,32}$' THEN
        RAISE EXCEPTION 'Nom d’utilisateur invalide.';
    END IF;

    INSERT INTO public.profiles (auth_user_id, username, name, email, phone)
    VALUES (
        NEW.id,
        supplied_username,
        COALESCE(NULLIF(BTRIM(NEW.raw_user_meta_data ->> 'name'), ''), supplied_username),
        COALESCE(NEW.email, ''),
        COALESCE(NEW.raw_user_meta_data ->> 'phone', '')
    );
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created_profile ON auth.users;
CREATE TRIGGER on_auth_user_created_profile
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.create_member_profile();

CREATE OR REPLACE FUNCTION public.sync_profile_email()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF NEW.email IS DISTINCT FROM OLD.email THEN
        UPDATE public.profiles SET email = COALESCE(NEW.email, ''), updated_at = NOW()
        WHERE auth_user_id = NEW.id;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_email_updated_profile ON auth.users;
CREATE TRIGGER on_auth_email_updated_profile
AFTER UPDATE OF email ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.sync_profile_email();

CREATE OR REPLACE FUNCTION public.protect_profile_roles()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF NEW.email IS DISTINCT FROM OLD.email AND NOT EXISTS (
        SELECT 1 FROM auth.users WHERE id = OLD.auth_user_id AND email = NEW.email
    ) THEN
        RAISE EXCEPTION 'L’adresse e-mail doit être modifiée via Supabase Auth.';
    END IF;
    IF NOT public.is_superadmin() AND (
        NEW.role IS DISTINCT FROM OLD.role OR
        NEW.bureau_role IS DISTINCT FROM OLD.bureau_role OR
        NEW.permissions_json IS DISTINCT FROM OLD.permissions_json OR
        NEW.auth_user_id IS DISTINCT FROM OLD.auth_user_id OR
        (NEW.is_active IS DISTINCT FROM OLD.is_active AND NEW.is_active)
    ) THEN
        RAISE EXCEPTION 'Seul le super-administrateur peut modifier les rôles et autorisations.';
    END IF;
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS protect_profile_roles_before_update ON public.profiles;
CREATE TRIGGER protect_profile_roles_before_update
BEFORE UPDATE ON public.profiles
FOR EACH ROW EXECUTE FUNCTION public.protect_profile_roles();

CREATE OR REPLACE FUNCTION public.guard_app_data_write()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    transaction_item JSONB;
    old_data JSONB := '[]'::jsonb;
BEGIN
    IF NEW.data_key <> 'transactions' OR public.can_manage_finance() THEN
        NEW.updated_at := NOW();
        RETURN NEW;
    END IF;

    IF TG_OP = 'UPDATE' THEN
        old_data := OLD.data_json;
        IF NOT (NEW.data_json @> OLD.data_json) THEN
            RAISE EXCEPTION 'Un membre ne peut pas modifier ou supprimer les transactions existantes.';
        END IF;
    END IF;

    IF jsonb_typeof(NEW.data_json) <> 'array' THEN
        RAISE EXCEPTION 'Les transactions doivent être une liste.';
    END IF;

    FOR transaction_item IN SELECT value FROM jsonb_array_elements(NEW.data_json)
    LOOP
        IF NOT (old_data @> jsonb_build_array(transaction_item)) AND (
            transaction_item ->> 'status' <> 'pending' OR
            transaction_item ->> 'createdBy' IS DISTINCT FROM public.current_username()
        ) THEN
            RAISE EXCEPTION 'Un membre ne peut ajouter que ses transactions en attente.';
        END IF;
    END LOOP;

    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS guard_app_data_before_write ON public.app_data;
CREATE TRIGGER guard_app_data_before_write
BEFORE INSERT OR UPDATE ON public.app_data
FOR EACH ROW EXECUTE FUNCTION public.guard_app_data_write();

CREATE OR REPLACE FUNCTION public.guard_message_update()
RETURNS TRIGGER
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
    IF NEW.sender_id IS DISTINCT FROM OLD.sender_id OR
        NEW.receiver_id IS DISTINCT FROM OLD.receiver_id OR
        NEW.id IS DISTINCT FROM OLD.id OR
        (NEW.payload - 'read' - 'pinned') IS DISTINCT FROM (OLD.payload - 'read' - 'pinned') THEN
        RAISE EXCEPTION 'Les informations principales d’un message ne sont pas modifiables.';
    END IF;
    IF NEW.payload -> 'read' IS DISTINCT FROM OLD.payload -> 'read'
        AND public.current_profile_id() <> OLD.receiver_id THEN
        RAISE EXCEPTION 'Seul le destinataire peut marquer un message comme lu.';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS guard_message_before_update ON public.messages;
CREATE TRIGGER guard_message_before_update
BEFORE UPDATE ON public.messages
FOR EACH ROW EXECUTE FUNCTION public.guard_message_update();

